/* Every string on /shop and /shop/:id that an admin may change.
   lib/copy.js

   ── One home per string, and no defaults table ────────────────────────────

   VANCE-HQ keeps defaults in code and overrides in a database, and spends a
   good deal of lib/content.js keeping the two from forking. There is no
   database here — the editor commits — so the fork cannot happen, and the
   simpler arrangement is available: every string lives in exactly ONE file,
   and that file is the one the site serves.

     a string you can see in the markup   →   shop.html / product.html
     a string a script prints             →   js/copy.js

   The schema below says which, for each key. It does NOT hold the values.
   Nothing in this repo holds a second copy of a string, so nothing can drift
   out of step with the page.

   ── js/copy.js is machine-written, and that is what makes it parseable ────

   It is a plain browser script, loaded by an ordinary <script> tag before
   shop.js and product.js — no fetch, no build step, no async ordering to get
   wrong. The server reads the same file by finding the object and parsing it
   as JSON, which is only safe because the file is never written by hand: the
   save endpoint rewrites it whole, in this exact shape, every time.
   test/copy.test.js is what keeps that promise honest.
*/

