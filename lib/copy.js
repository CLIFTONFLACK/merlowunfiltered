/* ── Sanitising ────────────────────────────────────────────────────────────

   Applied on the way IN, at the one door that writes, and kept next to the
   schema that says what a field IS. Splitting "what a heading may contain"
   from "what a heading is" across two files is how the two stop agreeing.
   ────────────────────────────────────────────────────────────────────────── */

/* Whitespace, including the non-breaking space a browser inserts on its own
   while you type. It is a different character from the one you meant, it
   compares unequal, and so it reads as an edit nobody made. Written as an
   escape rather than as itself so it is visible in the source. */
const SPACE = /[\s ]+/g;

/**
 * Plain text: one line, trimmed, capped, control characters gone.
 *
 * Filtered by code point rather than by a regex class, because the class has
 * to spell the control range as escapes, and an editor that helpfully turns
 * those escapes back into the characters themselves leaves a literal NUL
 * sitting invisibly in the source. This cannot be got wrong by looking at it.
 *
 * @returns {string|null} null when nothing is left, which every caller reads
 *   as "leave this field alone" rather than as "set it to empty". An empty
 *   heading is never what anybody meant, and it is what a slipped keystroke
 *   in a contenteditable produces.
 */
function text(value, max = LIMITS.line) {
  if (typeof value !== 'string') return null;

  const stripped = Array.from(value)
    .filter((ch) => {
      const c = ch.codePointAt(0);
      if (c < 0x20 || c === 0x7f) return false;       // C0 controls and DEL
      if (c >= 0x200b && c <= 0x200d) return false;   // zero-width space, ZWNJ, ZWJ
      if (c === 0xfeff) return false;                 // byte-order mark
      return true;
    })
    .join('');

  const clean = stripped.replace(SPACE, ' ').trim().slice(0, max);
  return clean || null;
}

/**
 * A destination.
 *
 * http and https ONLY. `javascript:` in an href executes on click, so this is
 * an allowlist on the scheme and never a blocklist of the bad ones — a
 * blocklist is where `JavaScript:`, a leading tab and an embedded newline get
 * through, because they are all the same URL to a browser and different
 * strings to a test.
 *
 * The string is PARSED rather than pattern-matched, and that buys two things a
 * `/^https?:/` test does not. It rejects what is not a URL at all — `https://`,
 * `http://[`, `http:// example.com` all begin with a scheme we allow and are
 * none of them a link, so a prefix test puts them in the page as an href that
 * goes nowhere. And it returns a NORMALISED value, which is what lets
 * lib/content.js tell a real edit from a re-save (see the note there).
 *
 * Every editable URL on this site is a link a visitor is expected to click, so
 * there is no case for allowing a third scheme, and none for allowing a
 * relative one either: these point at other people's platforms.
 */
function url(value) {
  if (typeof value !== 'string') return null;
  const raw = value.trim().slice(0, LIMITS.url);
  if (!raw) return null;
  let parsed;
  try {
    parsed = new URL(raw);
  } catch {
    return null;                       // not a URL at all, including a relative one
  }
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return null;
  return parsed.href;
}

/** One field, by the rules its schema entry gives it. An unknown key is null. */
function sanitise(key, value) {
  const field = BY_KEY.get(key);
  if (!field) return null;
  return field.kind === 'url' ? url(value) : text(value, field.max);
}

/**
 * Sanitise a whole incoming document, keeping only known keys that survived.
 * Anything rejected is simply absent, and an absent key means "unchanged" —
 * so a hostile or malformed field leaves no trace at all.
 */
function sanitiseAll(incoming) {
  const out = {};
  if (!incoming || typeof incoming !== 'object') return out;
  for (const [key, value] of Object.entries(incoming)) {
    const clean = sanitise(key, value);
    if (clean !== null) out[key] = clean;
  }
  return out;
}

/* ── js/copy.js, read and written ─────────────────────────────────────────── */

/**
 * Pull the object back out of the generated file.
 *
 * Between the first '{' after the assignment and the last '}' is JSON, because
 * renderClientCopy is the only thing that ever writes this file and it writes
 * JSON.stringify's output. Anything else is a file somebody has edited into a
 * shape this cannot read, and the honest answer to that is null rather than a
 * guess — the caller turns it into a refusal to save over work it cannot see.
 *
 * @returns {object|null}
 */
function readClientCopy(source) {
  if (typeof source !== 'string') return null;
  const assign = source.indexOf(OPEN);
  if (assign < 0) return null;
  const open = source.indexOf('{', assign);
  const close = source.lastIndexOf('}');
  if (open < 0 || close < open) return null;
  try {
    const parsed = JSON.parse(source.slice(open, close + 1));
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : null;
  } catch {
    return null;
  }
}

/**
 * Write the file.
 *
 * Keys come out in schema order rather than in whatever order the browser
 * happened to send them, so a diff of this file shows the edit and not a
 * reshuffle. Only keys the schema knows are written: a save cannot grow the
 * file a field the site has no code to print.
 */
function renderClientCopy(values) {
  const ordered = {};
  for (const key of jsKeys()) {
    if (typeof values?.[key] === 'string') ordered[key] = values[key];
  }
  return `${HEADER}\n${OPEN}${JSON.stringify(ordered, null, 2)};\n`;
}

